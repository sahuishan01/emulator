#!/usr/bin/env python3
"""Build our original assembly fixtures with LLVM, independently of the interpreter."""

import argparse
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes without writing files")
    parser.add_argument("--llvm-mc", default="llvm-mc-19")
    parser.add_argument("--llvm-objcopy", default="llvm-objcopy-19")
    parser.add_argument("--llvm-ld", default="ld.lld-19")
    args = parser.parse_args()
    examples = Path(__file__).resolve().parent.parent / "examples"
    sources = [*sorted((examples / "a64").glob("*.S")), *sorted((examples / "homebrew").glob("*.S"))]
    with tempfile.TemporaryDirectory(prefix="emulator-a64-") as temporary:
        for source in sources:
            obj = Path(temporary) / "fixture.o"
            elf = Path(temporary) / "fixture.elf"
            output = Path(temporary) / "fixture.bin"
            subprocess.run([args.llvm_mc, "-triple=aarch64", "-filetype=obj", str(source), "-o", str(obj)], check=True)
            subprocess.run([args.llvm_ld, "-Ttext=0", "--entry=0", str(obj), "-o", str(elf)], check=True)
            subprocess.run([args.llvm_objcopy, "-O", "binary", "--only-section=.text", str(elf), str(output)], check=True)
            target = source.with_suffix(".nro" if source.parent.name == "homebrew" else ".bin")
            data = output.read_bytes()
            if args.check:
                if not target.exists() or target.read_bytes() != data:
                    raise SystemExit(f"Fixture differs from LLVM assembly: {target.name}")
            else:
                target.write_bytes(data)
            print(f"{source.name}: {len(data)} bytes {'verified' if args.check else 'assembled'}")


if __name__ == "__main__":
    main()
