//! Emit host fixture data using our tested Rust reference decoder.
use emulator_texture::decode_bc1_rgba8;
use std::fmt::Write;

fn main() {
    let mut input = Vec::new();
    let cases = [
        (0xf800_u16, 0x07e0_u16, 0xe4e4e4e4_u32),
        (0x001f, 0xf800, 0xe4e4e4e4),
        (0, 0, 0xe4e4e4e4),
        (0xffff, 0, 0x1b1b1b1b),
        (0x0821, 0, 0xe4e4e4e4),
        (0x1234, 0xcdef, 0x01234567),
        (0xabcd, 0x1357, 0xfedcba98),
        (0xf800, 0xf800, 0xffffffff),
    ];
    for y in 0..16 {
        for x in 0..16 {
            let (a, b, selectors) = cases[(x + 3 * y) % cases.len()];
            input.extend_from_slice(&a.to_le_bytes());
            input.extend_from_slice(&b.to_le_bytes());
            input.extend_from_slice(&selectors.to_le_bytes());
        }
    }
    let reference = decode_bc1_rgba8(&input, 64, 64).unwrap();
    let mut header = String::from("// Generated by cargo run -p emulator-texture --example bc1_fixture.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace bc1_fixture {\n");
    for (name, bytes) in [("input", input), ("rgba8", reference)] {
        writeln!(
            header,
            "inline constexpr std::array<std::uint32_t, {}> {name} = {{",
            bytes.len() / 4
        )
        .unwrap();
        for row in bytes.chunks(32) {
            header.push_str("    ");
            for word in row.chunks_exact(4) {
                write!(
                    header,
                    "0x{:08x}, ",
                    u32::from_le_bytes(word.try_into().unwrap())
                )
                .unwrap();
            }
            header.pop();
            header.push('\n');
        }
        header.push_str("};\n");
    }
    header.push_str("} // namespace bc1_fixture\n");
    print!("{header}");
}
